"""PERKESO contribution tables -> src/data/perkeso/2026-06.ts.

Act 4 (SOCSO) with Lindung 24 (SKBBK): Lampiran 1 of PERKESO's "Soalan Lazim Skim LINDUNG 24 Jam" FAQ
(docs/sources/perkeso/lindung24-faq-2026.pdf, from perkeso.gov.my/images/borang/lindung24jam/SoalanLazimLindung24Jam.pdf),
"Kadar caruman baharu merangkumi SKBBK", from June 2026 wages. 65 bands, ceiling RM6,000. Each row:
first category employer, employee invalidity, employee SKBBK, total; second category employer, employee SKBBK, total.
The script refuses to write if a row's shares != its total, the two SKBBK columns differ, bands are not
increasing, or a PDF is not the expected file.

Act 800 (EIS): docs/sources/perkeso/kadar-caruman-akta-800-2024-10-10.pdf (perkeso.gov.my/images/dokumen/
101024 - Kadar Caruman Akta 800.pdf) is one scanned image, so it cannot be parsed. Its 65 rows have the same bands;
EIS_READ below is every employer (= employee) share read by eye from that image on 2026-11-02. The script also
checks it equals 0.2% of the band midpoint rounded up to 5 sen, so a typo in either fails.
Needs pypdf (pip install pypdf).

    python3 scripts/perkeso/caruman.py
"""

import hashlib
import json
import math
import pathlib
import re
import sys

from pypdf import PdfReader

ROOT = pathlib.Path(__file__).resolve().parents[2]
FAQ = ROOT / "docs/sources/perkeso/lindung24-faq-2026.pdf"
EIS_PDF = ROOT / "docs/sources/perkeso/kadar-caruman-akta-800-2024-10-10.pdf"
OUT = ROOT / "src/data/perkeso/2026-06.ts"
SHA = {
    FAQ: "f426c8cf46de5cbc6455abba512dc7ef2b289de2679cc3a3f39dba8b46d65f11",
    EIS_PDF: "3499fec4271b45ae3e3055b2071075f96f65dc451775ed23adf39f9deec5376a",
}
# Sen, rows 1-65 of the Act 800 image.
EIS_READ = [5, 10, 15, 20, 25, 35, 50, 70, 90] + list(range(110, 1191, 20)) + [1190]

for pdf, sha in SHA.items():
    digest = hashlib.sha256(pdf.read_bytes()).hexdigest()
    if digest != sha:
        sys.exit(f"unexpected {pdf.name} ({digest}) - new table? update SHA and re-check by hand")

text = "\n".join(p.extract_text() or "" for p in PdfReader(str(FAQ)).pages)
start = text.index("LAMPIRAN 1")
body = text[start : text.index("SKIM LINDUNG 24 JAM / SKIM KEMALANGAN", start)]
sen = lambda s: round(float(s.replace(",", "")) * 100)
rows = re.findall(r"\n(\d{1,2})\.\s*(.*?)((?:RM[\d,]+\.\d{2} ?){7})", body, re.S)
if [int(n) for n, _, _ in rows] != list(range(1, 66)):
    sys.exit(f"expected rows 1-65, got {[n for n, _, _ in rows]}")

bands, first, second = [], [], []
for n, desc, amounts in rows:
    v = [sen(x) for x in re.findall(r"RM([\d,]+\.\d{2})", amounts)]
    if v[0] + v[1] + v[2] != v[3] or v[4] + v[5] != v[6] or v[2] != v[5]:
        sys.exit(f"row {n}: shares do not add up {v}")
    limits = re.findall(r"RM([\d,]+)", desc)
    bands.append(int(limits[-1].replace(",", "")) if "tidak" in desc or "hingga" in desc else None)
    first.append(v[:3])  # employer, employee invalidity, employee SKBBK
    second.append([v[4], v[5]])  # employer, employee SKBBK

if bands[-1] is not None or bands[:-1] != sorted(bands[:-1]) or bands[-2] != 6000:
    sys.exit(f"bands not increasing to RM6,000 + one open band: {bands}")
bands = bands[:-1]  # upper bounds (RM) of rows 1-64; row 65 = over RM6,000

lower = [0] + bands
mid = [(lo + hi) / 2 for lo, hi in zip(lower, bands)] + [(bands[-2] + bands[-1]) / 2]
formula = [math.ceil(round(m * 0.2, 6) / 5) * 5 for m in mid]
if len(EIS_READ) != 65 or EIS_READ != formula:
    sys.exit(f"EIS_READ (image) != 0.2% of band midpoint:\n{EIS_READ}\n{formula}")

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(
    "// GENERATED by scripts/perkeso/caruman.py - do not edit.\n"
    "// PERKESO Act 4 (SOCSO, incl. Lindung 24 / SKBBK from June 2026 wages) and Act 800 (EIS) contribution tables.\n"
    f"// Sources: docs/sources/perkeso/lindung24-faq-2026.pdf Lampiran 1 (sha256 {SHA[FAQ]}),\n"
    f"// docs/sources/perkeso/kadar-caruman-akta-800-2024-10-10.pdf (sha256 {SHA[EIS_PDF]}).\n"
    "// bands: upper bound (RM) of rows 1-64, a row covers wages above the previous bound; row 65 = over RM6,000.\n"
    "// Amounts in sen. pertama = first category [employer, employee invalidity, employee SKBBK];\n"
    "// kedua = second category [employer, employee SKBBK]; sip = EIS share, the same for employer and employee.\n"
    "export const PERKESO_2026_06 = "
    + json.dumps({"bands": bands, "pertama": first, "kedua": second, "sip": EIS_READ}, separators=(",", ":"))
    + ";\n"
)
print(f"wrote {OUT.relative_to(ROOT)}: {len(first)} rows, last {first[-1]} / {second[-1]} / EIS {EIS_READ[-1]}")
